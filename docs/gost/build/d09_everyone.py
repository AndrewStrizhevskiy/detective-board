    d.h(1, "Чего проект пока НЕ умеет")
    d.bul(["**Не угадывает виновного надёжно.** Опытный режим («матрица подозреваемых») лежит в отдельной ветке `feat/suspects-matrix`, в основном коде его нет. На тесте из 8 рассказов ни один метод не победил простые приёмы вроде «кто чаще упомянут». На 8 рассказах для разработки лучший из примерно 35 вариантов угадал 4 из 8, но он отбирался на этих же рассказах, цифра завышена. На 6 совсем новых рассказах (отец Браун) тот же метод назвал виновного первым 2 раза из 6, ровно как «самый упоминаемый»; интервал 0,10–0,70; один оправданный человек был назван первым. Не обвинять невиновного получается только ценой отказа отвечать. Кто виновен и где обрезать текст, отметил ИИ – нужна проверка человеком (`docs/spike/results/suspects-20261030.md` на той ветке).",
           "**Сама почти не находит противоречия.** Из 12 противоречий в контрольном наборе правила нашли 0. На 19 из 20 рассказов не нашли ничего. Причина: из текста модель редко вытаскивает пары «кто + где + когда» (у 0,7 % высказываний). Единственная находка сделана на восьми карточках, введённых вручную.",
           "**Слабо запоминает, кто где был.** Целевой проход на 159 кусочках оставил 16 фактов (большая модель) и 7 (маленькая); ни у одного нет дня рассказа. Эталон для проверки – всего 4 строгих факта, поэтому качество оценить нельзя (`docs/spike/results/presence-pass-server-20261029.md`).",
           "**Не лучше простого поиска.** Агент 13 из 30 против 11 из 30 – разница не значима. На другой выборке (dev, 34 вопроса) агент хуже: 12 против 15.",
           "**Эталон не проверен человеком.** Вопросы и правильные ответы для измерений написал ИИ.",
           "**Только английские рассказы.** Русский вопрос переводится моделью; качество для русского отдельно не измерено.",
           "**Одна проверка установки.** Офлайн-пакет проверен на одном ноутбуке, а не на двух. Скорость измерена не в чистых условиях (шли другие программы)."])

