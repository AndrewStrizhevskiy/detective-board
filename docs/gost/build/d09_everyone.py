           "**«Следователь»** – это правила R1–R3. Они берут карточки с доски и проверяют их без участия модели.",
           "**«Судья»** проверяет каждую цитату: она должна найтись в тексте слово в слово. Не нашлась – вместо ответа будет отказ.",
