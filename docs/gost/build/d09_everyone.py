         ["Граф", "Доска из карточек и ниток между ними."],
         ["Индекс", "Список для быстрого поиска, как указатель в конце книги."],
         ["Правило", "Короткая проверка без нейросети: результат всегда один и тот же."],
         ["MCP", "Договорённость о том, как агент вызывает инструменты (например, правила)."],
