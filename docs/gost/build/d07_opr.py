        "Программа не делает выводов о виновности и не заменяет чтение рассказа: вывод правила следует из извлечённых фактов, а извлечение ошибается.",
        "Автоматически построенный граф содержит очень мало фактов, пригодных для правил (структурированные утверждения о присутствии – 0,7 % высказываний, `docs/spike/results/graph-sanity-20261028.md`), поэтому проверка алиби и противоречий на произвольном рассказе чаще вернёт «неизвестно» или пустой результат; уверенные находки есть только для курируемых демонстрационных случаев.",
