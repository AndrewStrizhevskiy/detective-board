"""Презентация проекта: python3 make_pptx.py -> ../09-prezentaciya.pptx (+PDF через LibreOffice)."""
import os
import subprocess
import sys

from pptx_min import ACCENT, INK, MUTED, SOFT, WARN, Deck

AUTHORS = ["Верховых Егор", "Стрижевский Андрей", "Парамонов Даниил", "Приц Артём"]
OUT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LO = os.path.expanduser("~/Applications/LibreOffice.app/Contents/MacOS/soffice")

d = Deck("Детективная доска (Detective Board)", AUTHORS)


def slide(title):
    s = d.add()
    s.title(title)
    return s


# 1 титульный
s = d.add()
s.text(0.7, 1.0, 11.9, 0.5, [("Проект", 22, False, MUTED, "l", 0)], "Подпись")
s.title("Детективная доска", 54, 1.5, 1.2)
s.text(0.7, 2.7, 11.9, 0.6, [("Detective Board", 28, False, INK, "l", 0)], "Название латиницей")
s.text(0.7, 3.4, 11.9, 0.9, [("Локальный офлайн-следователь по 20 рассказам о Шерлоке Холмсе", 24, False, INK, "l", 0)], "Тема")
s.text(0.7, 4.6, 8, 1.7, [("Авторы:", 20, True, MUTED, "l", 4)] + [(a, 22, False, INK, "l", 2) for a in AUTHORS], "Авторы")
s.text(0.7, 6.5, 6, 0.4, [("30.10.2026", 20, False, MUTED, "l", 0)], "Дата")

# 2 цель и задачи
s = slide("Цель и задачи")
s.lines(["Цель: отвечать по тексту рассказов и показывать, на чём держится ответ.",
         "1. Достать из текста факты вместе с дословными цитатами.",
         "2. Проверить факты правилами, а не мнением модели.",
         "3. Честно отказываться, если в тексте ответа нет.",
         "4. Измерить качество и записать слабые места."], sz=26)
s.number()

# 3 проблема
s = slide("Зачем это нужно")
s.lines(["Обычная языковая модель отвечает уверенно, даже когда не знает.",
         "Она выдумывает факты и цитаты.",
         "Без поиска по тексту верный ответ только на 3 из 30 вопросов (test, n=30)."], sz=28)
s.box(0.7, 5.2, 11.9, 1.0, "Наш ответ: цитата из текста или отказ", 28, SOFT, ACCENT, True)
s.number()

# 4 архитектура
s = slide("Как устроено")
names = ["20 рассказов\n596 фрагментов", "Модель\nизвлекает факты", "Граф фактов\nс цитатами", "Правила\nR1, R2, R3", "Агент\nответ или отказ", "Доска\nи трасса"]
x = 0.7
for i, t in enumerate(names):
    s.box(x, 2.6, 1.7, 1.9, t, 18, SOFT if i not in (3,) else "DDE5F0", INK, False, f"Этап {i + 1}")
    if i < 5:
        s.arrow(x + 1.7, 3.55, x + 2.04, 3.55)
    x += 2.04
s.text(0.7, 5.2, 11.9, 1.2, [("Модель угадывает, правила проверяют.", 26, True, ACCENT, "l", 8), ("Всё работает на одном ноутбуке без сети.", 24, False, INK, "l", 0)], "Подпись")
s.number()

# 5 метки
s = slide("Откуда взят каждый факт")
labels = [("extracted", "достала модель;\nможет ошибаться"), ("derived", "вывело правило;\nесть объяснение"), ("conditional", "правило на\nсомнительном факте")]
x = 0.7
for t, sub in labels:
    s.box(x, 2.2, 3.8, 2.4, f"{t}\n{sub}", 24, SOFT, INK, False, t)
    x += 4.05
s.text(0.7, 5.2, 11.9, 1.0, [("В демо есть ещё curated: факты введены вручную, проверка человеком впереди.", 24, False, INK, "l", 0)], "Подпись")
s.number()

# 6 правила
s = slide("Три правила")
s.lines(["R1. Человек не может быть в двух местах сразу.",
         "R2. Порядок событий не замыкается в круг.",
         "R3. Слова свидетеля не спорят с установленным фактом.",
         "Нет данных — ответ «неизвестно», а не «всё согласовано»."], sz=28)
s.number()

# 7 результаты
s = slide("Результат: вопросы с ответом или отказом")
vals = [("Только модель", 3, "999999"), ("Только поиск", 11, "999999"), ("Агент", 13, ACCENT)]
x = 1.2
for name, v, col in vals:
    h = 3.0 * v / 13
    s.box(x, 5.4 - h, 2.6, h, "", 12, col, INK, False, name)
    s.text(x, 5.4 - h - 0.55, 2.6, 0.5, [(f"{v} из 30", 26, True, INK, "ctr", 0)], f"Значение {name}")
    s.text(x - 0.2, 5.5, 3.0, 0.5, [(name, 20, False, INK, "ctr", 0)], f"Подпись {name}")
    x += 3.7
s.text(0.7, 6.15, 11.9, 0.5, [("Тест на 30 вопросах; метки ответов размечены автоматически, человек не проверял.", 16, False, MUTED, "l", 0)], "Примечание")
s.number()

# 8 слабые места
s = slide("Что пока не работает")
s.lines(["Правила на автоматическом графе: найдено 0 из 12 противоречий.",
         "Извлечение «кто где был»: оставлено 16 и 7 фактов на 159 фрагментах.",
         "Из них ни один не привязан ко дню рассказа.",
         "Эталон для проверки — всего 4 строгих факта."], sz=26)
s.text(0.7, 6.3, 11.9, 0.5, [("Источник: отчёт о проходе присутствия (PR #29).", 16, False, MUTED, "l", 0)], "Источник")
s.number()

# 9 скорость и тесты
s = slide("Скорость, интерфейс, тесты")
s.lines(["Ответ на ноутбуке без GPU: медиана 28,4 с (замер не в чистом окне).",
         "Доска, 14 карточек: сдвиг 2400 → 225 мс, масштаб 2100 → 315 мс.",
         "Доска, 200 узлов: сдвиг 2060 → 384 мс, масштаб 13 900 → 2 780 мс.",
         "Шум на масштабе большой; на ноутбуке не измерено.",
         "Автотесты: 986 прошли за 9,6 с."], sz=26, gap=0.12)
s.text(0.7, 6.0, 11.9, 0.8, [("PR #30: время растеризации, headless Chromium, скриптовые сдвиг и масштаб. В покое картинка прежняя (отличие 1,5 из 255).", 16, False, MUTED, "l", 0)], "Примечание")
s.number()

# 10 виновный
s = slide("Угадывание виновного: ненадёжно")
s.lines(["Тест (8 рассказов, один прогон): ни один метод не лучше простых.",
         "Dev (8): лучший из ~35 вариантов угадал 4 из 8 – цифра завышена.",
         "6 новых рассказов: верно 2 из 6, как у «самого упоминаемого».",
         "Интервал 0,10–0,70; один оправданный назван первым.",
         "Не обвиняет невиновного – только ценой отказов."], sz=26, gap=0.12)
s.text(0.7, 6.0, 11.9, 0.8, [("Метки размечены автоматически, нужна проверка человеком. Эксперимент, в основной путь ответов не включён.", 16, False, MUTED, "l", 0)], "Оговорка")
s.number()

# 11 выводы
s = slide("Выводы")
s.lines(["Система отвечает цитатами и честно отказывается.",
         "Агент немного лучше голой модели; от простого поиска значимо не отличается.",
         "Правила точны, но автоматическому графу не хватает фактов.",
         "Дальше: проверка наборов человеком, установка на двух ноутбуках."], sz=26)
s.number()

# 12 источники
s = slide("Источники")
s.lines(["docs/spike/results/eval-2026-10-28-test-7b7b197-7857839ed9be-175321.md",
         "docs/spike/results/presence-pass-server-20261029.md",
         "docs/perf/laptop-20261029.md",
         "suspects-20261030.md",
         "PR #30 на GitHub: описание измерений"], sz=22)
s.number()

pptx = os.path.join(OUT, "09-prezentaciya.pptx")
d.save(pptx)
subprocess.run([LO, "--headless", "--convert-to", "pdf", "--outdir", OUT, pptx], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
print("ok", len(d.slides))
