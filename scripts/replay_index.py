#!/usr/bin/env python3
"""Write web/replay/index.json: the recordings the UI picker and key `c` offer (stdlib only).

Usage: python3 scripts/replay_index.py [--check]
Reads the `meta` of every web/replay/*.json and writes one row per file: file, question, kind
(real | fake | synthetic), recorded_at, seconds, and the demo step it backs; under "bare", one row
per web/replay/bare/*.json (bare-model answers for the split view, scripts/bare_recording.py).
Re-run after a recording is added or replaced; --check exits 1 if index.json is stale.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPLAY = Path(__file__).resolve().parents[1] / "web" / "replay"
INDEX = REPLAY / "index.json"

# Demo steps backed by a recording (docs/design/demo-script.md, running order); shown in the picker.
STEPS = {
    "real-g001-agent.json": "demo steps 0, 1, 4 (g001)",
    "real-wisteria-r1-curated.json": "demo step 2 (Wisteria R1, curated)",
    "real-refusal-baskerville.json": "demo step 3 (gate refusal, g047)",
}


def kind_of(meta: dict) -> str:
    if meta.get("label") == "RECORDING" and "real run" in str(meta.get("kind", "")):
        return "real"
    question, note = str(meta.get("question", "")), str(meta.get("note", ""))
    if question.startswith("SYNTHETIC") or "Hand-written" in note:
        return "synthetic"
    return "fake"


def build() -> dict:
    rows = []
    for path in sorted(REPLAY.glob("*.json")):
        if path.name == INDEX.name:
            continue
        data = json.loads(path.read_text())
        meta = data.get("meta", {}) if isinstance(data, dict) else {}
        row = {"file": path.name, "question": meta.get("question", ""), "kind": kind_of(meta)}
        for key in ("recorded_at", "seconds"):
            if key in meta:
                row[key] = meta[key]
        if path.name in STEPS:
            row["step"] = STEPS[path.name]
        rows.append(row)
    order = {"real": 0, "fake": 1, "synthetic": 2}
    steps = list(STEPS)
    rank = {f: i for i, f in enumerate(steps)}
    rows.sort(key=lambda r: (order[r["kind"]], rank.get(r["file"], len(steps)), r["file"]))
    bare = []
    for path in sorted((REPLAY / "bare").glob("*.json")):
        meta = json.loads(path.read_text()).get("meta", {})
        row = {"file": f"bare/{path.name}", "question": meta.get("question", "")}
        for key in ("qid", "model", "recorded_on", "seconds"):
            if key in meta:
                row[key] = meta[key]
        bare.append(row)
    note = "Generated by scripts/replay_index.py; do not edit by hand."
    return {"note": note, "recordings": rows, "bare": bare}


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if index.json is out of date")
    args = ap.parse_args()
    index = build()
    text = json.dumps(index, indent=1, ensure_ascii=False) + "\n"
    if args.check:
        ok = INDEX.exists() and INDEX.read_text() == text
        stale = "index.json is stale: run scripts/replay_index.py"
        print("index.json is up to date" if ok else stale)
        return 0 if ok else 1
    INDEX.write_text(text)
    print(f"wrote {INDEX.relative_to(REPLAY.parents[1])} ({len(index['recordings'])} recordings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
